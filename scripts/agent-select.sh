#!/usr/bin/env bash
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUNTIME_DIR="$APP_DIR/.runtime"
ENV_FILE="$RUNTIME_DIR/bookcompressor.env"
mkdir -p "$RUNTIME_DIR"

# shellcheck disable=SC1090
if [[ -f "$ENV_FILE" ]]; then
  set -a
  . "$ENV_FILE"
  set +a
fi

shell_quote() {
  python3 - "$1" <<'PY'
import shlex, sys
print(shlex.quote(sys.argv[1]))
PY
}

write_env() {
  local provider="$1"
  {
    echo "# Generated by scripts/agent-select.sh. Safe to edit."
    echo "BOOK_COMPRESSOR_INFERENCE_PROVIDER=$(shell_quote "$provider")"
    if [[ -n "${BOOK_COMPRESSOR_AGENT_COMMAND:-}" ]]; then
      echo "BOOK_COMPRESSOR_AGENT_COMMAND=$(shell_quote "$BOOK_COMPRESSOR_AGENT_COMMAND")"
    fi
    if [[ -n "${BOOK_COMPRESSOR_AGENT_ARGS:-}" ]]; then
      echo "BOOK_COMPRESSOR_AGENT_ARGS=$(shell_quote "$BOOK_COMPRESSOR_AGENT_ARGS")"
    fi
    if [[ -n "${BOOK_COMPRESSOR_AGENT_OUTPUT_MODE:-}" ]]; then
      echo "BOOK_COMPRESSOR_AGENT_OUTPUT_MODE=$(shell_quote "$BOOK_COMPRESSOR_AGENT_OUTPUT_MODE")"
    fi
    if [[ -n "${BOOK_COMPRESSOR_HERMES_PROVIDER:-}" ]]; then
      echo "BOOK_COMPRESSOR_HERMES_PROVIDER=$(shell_quote "$BOOK_COMPRESSOR_HERMES_PROVIDER")"
    fi
    if [[ -n "${BOOK_COMPRESSOR_OPENROUTER_DEFAULT_MODEL:-}" ]]; then
      echo "BOOK_COMPRESSOR_OPENROUTER_DEFAULT_MODEL=$(shell_quote "$BOOK_COMPRESSOR_OPENROUTER_DEFAULT_MODEL")"
    fi
  } >"$ENV_FILE"
  echo "Saved agent runtime: $provider ($ENV_FILE)"
}

detect_summary() {
  command -v hermes >/dev/null 2>&1 && echo "- Hermes CLI detected (recommended)" || echo "- Hermes CLI not found"
  command -v openclaw >/dev/null 2>&1 && echo "- OpenClaw CLI detected" || echo "- OpenClaw CLI not found"
  if [[ -n "${OPENROUTER_API_KEY:-${OPENROUTER_KEY:-${OPENROUTER_API_TOKEN:-}}}" ]]; then
    echo "- OpenRouter key detected"
  else
    echo "- OpenRouter key not found"
  fi
}

if [[ -n "${BOOK_COMPRESSOR_INFERENCE_PROVIDER:-}" && "${1:-}" != "--force" ]]; then
  echo "Agent runtime already selected: $BOOK_COMPRESSOR_INFERENCE_PROVIDER"
  echo "Run scripts/agent-select.sh --force to choose again."
  exit 0
fi

if [[ ! -t 0 ]]; then
  write_env "auto"
  exit 0
fi

echo "Choose the agent/model runtime for Book Compressor."
detect_summary
cat <<'EOF'

1) Hermes CLI (recommended)
2) OpenClaw CLI
3) OpenRouter API key
4) Custom agent command
5) Auto-detect at runtime (Hermes -> OpenClaw -> OpenRouter)
EOF
read -r -p "Selection [1]: " choice
choice="${choice:-1}"

case "$choice" in
  1) write_env "hermes" ;;
  2) write_env "openclaw" ;;
  3) write_env "openrouter" ;;
  4)
    read -r -p "Agent command path/name: " BOOK_COMPRESSOR_AGENT_COMMAND
    read -r -p 'Agent args JSON array or simple args ["{prompt}"]: ' BOOK_COMPRESSOR_AGENT_ARGS
    BOOK_COMPRESSOR_AGENT_ARGS="${BOOK_COMPRESSOR_AGENT_ARGS:-[\"{prompt}\"]}"
    read -r -p "Output mode stdout|last-line|json [stdout]: " BOOK_COMPRESSOR_AGENT_OUTPUT_MODE
    BOOK_COMPRESSOR_AGENT_OUTPUT_MODE="${BOOK_COMPRESSOR_AGENT_OUTPUT_MODE:-stdout}"
    write_env "agent-command"
    ;;
  5) write_env "auto" ;;
  *) echo "Unknown selection: $choice" >&2; exit 1 ;;
esac
